/**
 * One Spoonacular key for both platforms: `spoonacular.apiKey` in local.properties (git-ignored),
 * or the SPOONACULAR_API_KEY environment variable on CI. It is generated into shared code, so
 * neither the Android nor the iOS app needs its own secrets setup.
 */
val spoonacularApiKeyProvider: Provider<String> = providers
    .fileContents(rootProject.layout.projectDirectory.file("local.properties")).asText
    .map { text -> Properties().apply { load(text.reader()) }.getProperty("spoonacular.apiKey").orEmpty().trim() }
    .filter { it.isNotEmpty() }
    .orElse(providers.environmentVariable("SPOONACULAR_API_KEY"))
    .orElse("")

abstract class GenerateSecretsTask : DefaultTask() {
    @get:Input
    abstract val spoonacularApiKey: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val escaped = spoonacularApiKey.get()
            .replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        val file = outputDir.file("com/ankitt/thefoodhub/core/Secrets.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by :shared:generateSecrets from local.properties. Do not edit or commit.
            |package com.ankitt.thefoodhub.core
            |
            |internal object Secrets {
            |    const val SPOONACULAR_API_KEY: String = "$escaped"
            |}
            |""".trimMargin(),
        )
    }
}

val generateSecrets = tasks.register<GenerateSecretsTask>("generateSecrets") {
    spoonacularApiKey.set(spoonacularApiKeyProvider)
    outputDir.set(layout.buildDirectory.dir("generated/secrets/commonMain/kotlin"))
}

